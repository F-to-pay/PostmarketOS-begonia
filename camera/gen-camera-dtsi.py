#!/usr/bin/env python3
"""Generator of camera-begonia.dtsi (M0: sensor power + I2C buses).

The pins/slots are copied 1:1 from the vendor cust_mt6785_camera.dtsi (kernel-r-oss), the function names - from
mediatek,mt6785-pinfunc.h. Slot = the vendor sensor index: 0 MAIN, 1 SUB, 2 MAIN2, 3 SUB2, 4 MAIN3.
usage: gen-camera-dtsi.py > camera-begonia.dtsi
"""
# slot: (rst, pdn, vcama, vcamd, mclk_gpio, mclk_func)
SLOTS = {
    0: (118, 93, 114, 114, 116, 'CMMCLK0'),
    1: (124, 122, 123, 122, 120, 'CMMCLK2'),
    2: (125, 123, 123, 123, 121, 'CMMCLK3'),
    3: (119, 115, 195, 195, 117, 'CMMCLK1'),
    4: (197, 115, 195, 195, 196, 'CMMCLK4'),
}
SWITCH_SEL = 94   # MIPI mux sub <-> main3

out = []
w = out.append
w('// SPDX-License-Identifier: GPL-2.0')
w('/*')
w(' * EXPERIMENTAL (M0): Redmi Note 8 Pro (begonia) camera power and the sensor I2C buses.')
w(' * GENERATED by gen-camera-dtsi.py - do not edit by hand. The labels (pio, topckgen, camsys, spm, i2c2/4/7,')
w(' * camvcamio) are placed by make-cam-dtb.sh.')
w(' */')
w('')
w('#include <dt-bindings/power/mediatek,mt6785-power.h>')
w('#include <dt-bindings/clock/mediatek,mt6785-clk.h>')
w('#include <dt-bindings/pinctrl/mediatek,mt6785-pinfunc.h>')
w('#include <dt-bindings/gpio/gpio.h>')
w('')
w('&pio {')
for bus, (scl, sda) in {2: (112, 113), 4: (110, 111), 7: (198, 199)}.items():
    w(f'\tcam_i2c{bus}_pins: cam-i2c{bus}-pins {{')
    w('\t\tpins-bus {')
    w(f'\t\t\tpinmux = <PINMUX_GPIO{scl}__FUNC_SCL{bus}>,')
    w(f'\t\t\t\t <PINMUX_GPIO{sda}__FUNC_SDA{bus}>;')
    w('\t\t\tbias-pull-up;')
    w('\t\t};')
    w('\t};')
    w('')

names = []   # (pinctrl-name, label)


def gpio_state(label, gpio, level):
    w(f'\t{label}: {label.replace("_", "-")} {{')
    w('\t\tpins-cmd {')
    w(f'\t\t\tpinmux = <PINMUX_GPIO{gpio}__FUNC_GPIO{gpio}>;')
    w(f'\t\t\toutput-{level};')
    w('\t\t};')
    w('\t};')


for i, (rst, pdn, vcama, vcamd, mclk, func) in SLOTS.items():
    for nm, gpio in (('rst', rst), ('pdn', pdn), ('vcama', vcama), ('vcamd', vcamd)):
        for v, lv in ((0, 'low'), (1, 'high')):
            lab = f'cam{i}_{nm}{v}'
            gpio_state(f'{lab}', gpio, lv)
            names.append((f'cam{i}_{nm}{v}', lab))
    # MCLK: off = GPIO mode, low; on = the CMMCLKn function, 4 mA (like the vendor)
    w(f'\tcam{i}_mclk_off: cam{i}-mclk-off {{')
    w('\t\tpins-mclk {')
    w(f'\t\t\tpinmux = <PINMUX_GPIO{mclk}__FUNC_GPIO{mclk}>;')
    w('\t\t\toutput-low;')
    w('\t\t};')
    w('\t};')
    w(f'\tcam{i}_mclk_on: cam{i}-mclk-on {{')
    w('\t\tpins-mclk {')
    w(f'\t\t\tpinmux = <PINMUX_GPIO{mclk}__FUNC_{func}>;')
    w('\t\t\tdrive-strength = <4>;  /* mA (mainline: 2..16 step 2); the raw vendor 1 = 4 mA */')
    w('\t\t};')
    w('\t};')
    names.append((f'cam{i}_mclk_off', f'cam{i}_mclk_off'))
    names.append((f'cam{i}_mclk_on', f'cam{i}_mclk_on'))
    w('')
for v, lv in ((0, 'low'), (1, 'high')):
    gpio_state(f'cam_sw{v}', SWITCH_SEL, lv)
    names.append((f'sw{v}', f'cam_sw{v}'))
w('};')
w('')
# The camera buses 2/4/7 are multi-channel controllers (vendor: ch_offset_default = <0x100>, i2c2 also has
# ch_offset_ccu = <0x200>). The built-in i2c-mt65xx cannot do multi-channel (channel 0: timeout, 0 interrupts;
# shifting the base by +0x100 in DT: the first transaction passes, then the controller jams - the configuration must go to channel 0).
# Hence our own compatible -> the out-of-tree i2c-mt65xx-mch (i2c-mch/), the AP channel offset - mediatek,ch-offset.
for bus in (2, 4, 7):
    w(f'&i2c{bus} {{')
    w('\tcompatible = "xiaomi,mt6785-i2c-mch";')
    w('\tmediatek,ch-offset = <0x100>;')
    w('\tclock-frequency = <400000>;')
    w('\tpinctrl-names = "default";')
    w(f'\tpinctrl-0 = <&cam_i2c{bus}_pins>;')
    w('\tstatus = "okay";')
    w('};')
    w('')
w('&{/soc} {')
w('\tcamera_probe: camera-probe {')
w('\t\tcompatible = "xiaomi,begonia-cam-probe";')
w('\t\t/* TWO domains on purpose (like md-bringup): otherwise the kernel turns cam on at bind. The driver attaches cam itself. */')
w('\t\tpower-domains = <&spm MT6785_POWER_DOMAIN_CAM>, <&spm MT6785_POWER_DOMAIN_CONN>;')
w('\t\tpower-domain-names = "cam", "conn";')
w('\t\tclocks = <&topckgen CLK_TOP_CAMTG1>, <&topckgen CLK_TOP_CAMTG2>,')
w('\t\t\t <&topckgen CLK_TOP_CAMTG3>, <&topckgen CLK_TOP_CAMTG4>,')
w('\t\t\t <&topckgen CLK_TOP_CAMTG5>,')
w('\t\t\t <&topckgen CLK_TOP_UNIVPLL_192M_D8>,')
w('\t\t\t <&camsys CLK_CAM_TG>;')
w('\t\tclock-names = "tg0", "tg1", "tg2", "tg3", "tg4", "src24", "camtg";')
w('\t\tvcamio-supply = <&camvcamio>;')
w('\t\tpinctrl-names =')
w(',\n'.join(f'\t\t\t"{n}"' for n, _ in names) + ';')
for k, (_, lab) in enumerate(names):
    w(f'\t\tpinctrl-{k} = <&{lab}>;')
w('\t};')
w('};')
# ---------------- M1: OV8856 (MAIN3, slot 4) as the mainline sensor ovti,ov8856 ----------------
# Vendor: OV8856 on begonia - 2 MIPI lanes, MCLK 24 MHz (mainline expects 19.2 - only a warning).
# Power like the vendor (class C): PDN(115)=1, MCLK, DOVDD(vcamio), AVDD/DVDD = switch GPIO195, RST(197).
# avdd = switch 195, dvdd = a regulator PDN 115 on top of avdd (ov8856 has no pdn-gpio, but PDN must be raised).
# MCLK: cam-probe tg_keep=1 keeps all CAMTG1..5 at 24 MHz (the CMMCLK4->CAMTGn wiring is unknown).
M1 = '''
/ {
	cam4_avdd: cam4-avdd {
		compatible = "regulator-fixed";
		regulator-name = "cam4-avdd";
		regulator-min-microvolt = <2800000>;
		regulator-max-microvolt = <2800000>;
		gpio = <&pio 195 GPIO_ACTIVE_HIGH>;
		enable-active-high;
	};
	cam4_pdn: cam4-pdn {
		compatible = "regulator-fixed";
		regulator-name = "cam4-pdn";
		regulator-min-microvolt = <1200000>;
		regulator-max-microvolt = <1200000>;
		gpio = <&pio 115 GPIO_ACTIVE_HIGH>;
		enable-active-high;
		vin-supply = <&cam4_avdd>;
	};
};

&pio {
	/* MIPI mux: 1 = MAIN3 (OV8856), 0 = SUB (front). While there is one camera - keep MAIN3. */
	cam-mipi-sel-hog {
		gpio-hog;
		gpios = <94 GPIO_ACTIVE_HIGH>;
		output-high;
		line-name = "cam-mipi-sel";
	};
};

&i2c7 {
	ov8856: camera@10 {
		compatible = "ovti,ov8856";
		reg = <0x10>;
		clocks = <&topckgen CLK_TOP_CAMTG5>;
		clock-names = "xvclk";
		clock-frequency = <24000000>;
		assigned-clocks = <&topckgen CLK_TOP_CAMTG5>;
		assigned-clock-parents = <&topckgen CLK_TOP_UNIVPLL_192M_D8>;
		reset-gpios = <&pio 197 GPIO_ACTIVE_LOW>;
		dovdd-supply = <&camvcamio>;
		avdd-supply = <&cam4_avdd>;
		dvdd-supply = <&cam4_pdn>;
		pinctrl-names = "default";
		pinctrl-0 = <&cam4_mclk_on>;
		port {
			ov8856_ep: endpoint {
				data-lanes = <1 2>;
				link-frequencies = /bits/ 64 <720000000 360000000>;
			};
		};
	};
};'''
w(M1)

# ---------------- M2 step 1: SENINF test model (module seninf/seninf-tm.ko) ----------------
M2 = '''
&{/soc} {
	seninf_tm: seninf-tm@1a040000 {
		compatible = "xiaomi,begonia-seninf-tm";
		reg = <0 0x1a040000 0 0x6000>;
		/* two domains (like md-bringup/cam-probe): the driver turns cam on by itself on command */
		power-domains = <&spm MT6785_POWER_DOMAIN_CAM>, <&spm MT6785_POWER_DOMAIN_CONN>;
		power-domain-names = "cam", "conn";
		clocks = <&camsys CLK_CAM_MAIN>, <&camsys CLK_CAM_GALS>, <&camsys CLK_CAM_TG>,
			 <&camsys CLK_CAM_SENINF>, <&topckgen CLK_TOP_SENINF0>,
			 <&topckgen CLK_TOP_SENINF1>, <&topckgen CLK_TOP_SENINF2>;
		clock-names = "cam-main", "cam-gals", "cam-tg", "cam-seninf",
			      "top-seninf0", "top-seninf1", "top-seninf2";
	};
};'''
w(M2)

# ---------------- M2 step 2: CAMSV0 (module camsv/camsv-tm.ko) ----------------
M2B = '''
&{/soc} {
	camsv_tm: camsv-tm@1a050000 {
		compatible = "xiaomi,begonia-camsv-tm";
		reg = <0 0x1a040000 0 0x6000>,	/* SENINF */
		      <0 0x1a050000 0 0x1000>,	/* CAMSV0 */
		      <0 0x1a000000 0 0x1000>,	/* camsys */
		      <0 0x11c80000 0 0xc000>;	/* MIPI RX ANA/DPHY (CSI0..2) */
		power-domains = <&spm MT6785_POWER_DOMAIN_CAM>, <&spm MT6785_POWER_DOMAIN_CONN>;
		power-domain-names = "cam", "conn";
		clocks = <&camsys CLK_CAM_MAIN>, <&camsys CLK_CAM_GALS>, <&camsys CLK_CAM_TG>,
			 <&camsys CLK_CAM_SENINF>, <&camsys CLK_CAM_SV0>, <&camsys CLK_CAM_SV1>,
			 <&camsys CLK_CAM_LARB6>, <&camsys CLK_CAM_LARB7>,
			 <&topckgen CLK_TOP_SENINF0>, <&topckgen CLK_TOP_SENINF1>, <&topckgen CLK_TOP_SENINF2>;
		clock-names = "cam-main", "cam-gals", "cam-tg", "cam-seninf", "cam-sv0", "cam-sv1",
			      "cam-larb6", "cam-larb7", "top-seninf0", "top-seninf1", "top-seninf2";
		mediatek,larb = <&camlarb6>;
	};
};'''
w(M2B)
print('\n'.join(out))
